// leanDecoders and leanEncoders hold the helper text per Lean type.
func leanIntDecoder(lean string) string {
	if strings.HasPrefix(lean, "UInt") {
		return fmt.Sprintf(`def dec%[1]s (j : Json) : Except String %[1]s := do
  let i ← j.getInt?
  if i < 0 then throw s!"integer {i} is out of range for %[1]s"
  let n := i.toNat
  if (%[1]s.ofNat n).toNat == n then pure (%[1]s.ofNat n) else throw s!"integer {i} is out of range for %[1]s"
`, lean)
	}
	return fmt.Sprintf(`def dec%[1]s (j : Json) : Except String %[1]s := do
  let i ← j.getInt?
  if (%[1]s.ofInt i).toInt == i then pure (%[1]s.ofInt i) else throw s!"integer {i} is out of range for %[1]s"
`, lean)
}

// leanCodec returns the decoder and encoder expressions for t and adds
// the helper definitions it needs to defs.
func leanCodec(t hotspot.Type, defs map[string]string) (dec, enc string) {
	switch t.Kind {
	case hotspot.KindBool:
		defs["decBool"] = "def decBool (j : Json) : Except String Bool := j.getBool?\n"
		defs["encBool"] = "def encBool (x : Bool) : Json := toJson x\n"
		return "decBool", "encBool"
	case hotspot.KindString:
		defs["decString"] = "def decString (j : Json) : Except String String := j.getStr?\n"
		defs["encString"] = "def encString (x : String) : Json := toJson x\n"
		return "decString", "encString"
	case hotspot.KindList:
		d, e := leanCodec(*t.Elem, defs)
		defs["decArray"] = "def decArray {α : Type} (d : Json → Except String α) (j : Json) : Except String (Array α) := do\n  let xs ← j.getArr?\n  xs.mapM d\n"
		defs["encArray"] = "def encArray {α : Type} (e : α → Json) (xs : Array α) : Json := Json.arr (xs.map e)\n"
		return "(decArray " + d + ")", "(encArray " + e + ")"
	}
	l := t.Int.Lean
	switch {
	case l == "Int":
		defs["decInt"] = "def decInt (j : Json) : Except String Int := j.getInt?\n"
		defs["encInt"] = "def encInt (x : Int) : Json := toJson x\n"
	case strings.HasPrefix(l, "UInt"):
		defs["dec"+l] = leanIntDecoder(l)
		defs["enc"+l] = fmt.Sprintf("def enc%[1]s (x : %[1]s) : Json := toJson x.toNat\n", l)
	default:
		defs["dec"+l] = leanIntDecoder(l)
		defs["enc"+l] = fmt.Sprintf("def enc%[1]s (x : %[1]s) : Json := toJson x.toInt\n", l)
	}
	return "dec" + l, "enc" + l
}

// LeanHarness returns the text of the Lean program for h. importModule
// is the module that holds the model, such as Formal.Paranoid.UtilAdd.
// The model is called as <h.Identifier>.model.
func LeanHarness(h *hotspot.Hotspot, importModule string) string {
	defs := map[string]string{}
	decs := make([]string, len(h.Params))
	for i, p := range h.Params {
		decs[i], _ = leanCodec(p.Type, defs)
	}
	_, resEnc := leanCodec(h.Result, defs)
	keys := make([]string, 0, len(defs))
	for k := range defs {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	var b strings.Builder
	b.WriteString("-- Generated by paranoid for the differential test. Do not edit.\nimport Lean\nimport " + importModule + "\n\nopen Lean\n\nnamespace ParanoidDiff\n\n")
	for _, k := range keys {
		b.WriteString(defs[k] + "\n")
	}
	b.WriteString("def step (line : String) : Except String Json := do\n  let j ← Json.parse line\n  let args ← j.getArr?\n")
	fmt.Fprintf(&b, "  if args.size != %d then throw s!\"expected %d arguments, got {args.size}\"\n", len(h.Params), len(h.Params))
	call := h.Identifier + ".model"
	for i := range h.Params {
		fmt.Fprintf(&b, "  let a%d ← %s args[%d]!\n", i, decs[i], i)
		call += fmt.Sprintf(" a%d", i)
	}
	fmt.Fprintf(&b, "  pure (%s (%s))\n\n", resEnc, call)
	b.WriteString(`def runLine (line : String) : String :=
  match step line with
  | .ok v => (Json.mkObj [("ok", v)]).compress
  | .error e => (Json.mkObj [("error", Json.str e)]).compress

end ParanoidDiff

def main (args : List String) : IO UInt32 := do
  match args with
  | [inPath, outPath] =>
    let content ← IO.FS.readFile inPath
    let mut out := ""
    for line in content.splitOn "\n" do
      if line.trim.isEmpty then continue
      out := out ++ ParanoidDiff.runLine line ++ "\n"
    IO.FS.writeFile outPath out
    return 0
  | _ =>
    IO.eprintln "usage: harness <input> <output>"
    return 1
`)
	return b.String()
}
