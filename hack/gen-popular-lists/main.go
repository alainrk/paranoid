// Command gen-popular-lists regenerates the embedded top-package
// lists in internal/analyze/deps/popular/. It talks to public registry
// endpoints and is a development tool only; the shipped binary never
// runs it. Run from the repository root:
//
//	go run ./hack/gen-popular-lists
//
// Sources:
//   - npm: the npm-high-impact dataset (npm download counts)
//   - PyPI: the top-pypi-packages dataset (BigQuery download counts)
//   - crates: the crates.io API sorted by downloads
//
// There is no popularity signal for Go modules, so DEP004 does not
// cover Go and no list exists for it.
package main

import (
	"encoding/json"
	"fmt"
	"io"
	"net/http"
	"os"
	"regexp"
	"sort"
	"strings"
	"time"
)

const (
	listSize  = 1000
	userAgent = "paranoid-gen-popular-lists (github.com/alainrk/paranoid)"
	outDir    = "internal/analyze/deps/popular"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "error:", err)
		os.Exit(1)
	}
}

func run() error {
	for name, fetch := range map[string]func() ([]string, error){
		"npm.txt":    fetchNPM,
		"pypi.txt":   fetchPyPI,
		"crates.txt": fetchCrates,
	} {
		names, err := fetch()
		if err != nil {
			return fmt.Errorf("fetching %s: %w", name, err)
		}
		if len(names) < listSize/2 {
			return fmt.Errorf("%s: only %d names, refusing to write a stub list", name, len(names))
		}
		if err := writeList(name, names); err != nil {
			return err
		}
		fmt.Printf("wrote %s (%d names)\n", name, min(len(names), listSize))
	}
	return nil
}

// writeList writes up to listSize names, sorted, one per line.
func writeList(name string, names []string) error {
	if len(names) > listSize {
		names = names[:listSize]
	}
	sort.Strings(names)
	var b strings.Builder
	b.WriteString("# Generated by hack/gen-popular-lists. Do not edit by hand.\n")
	for _, n := range names {
		b.WriteString(n + "\n")
	}
	// Public data for the embedded list, not a secret.
	return os.WriteFile(outDir+"/"+name, []byte(b.String()), 0o644) // #nosec G306
}

// get fetches one URL with the tool's user agent.
func get(url string) ([]byte, error) {
	req, err := http.NewRequest(http.MethodGet, url, nil)
	if err != nil {
		return nil, err
	}
	req.Header.Set("User-Agent", userAgent)
	// Fixed public dataset URLs in a development-time generator.
	resp, err := http.DefaultClient.Do(req) // #nosec G704
	if err != nil {
		return nil, err
	}
	defer func() { _ = resp.Body.Close() }()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("%s: status %s", url, resp.Status)
	}
	return io.ReadAll(resp.Body)
}

// npmNameRe matches one quoted package name in the dataset file.
var npmNameRe = regexp.MustCompile(`'([^']+)'`)

// fetchNPM reads the npm-high-impact top-downloads list, a JS file
// exporting an array of names ordered by downloads.
func fetchNPM() ([]string, error) {
	body, err := get("https://raw.githubusercontent.com/wooorm/npm-high-impact/main/lib/top.js")
	if err != nil {
		return nil, err
	}
	var names []string
	for _, m := range npmNameRe.FindAllStringSubmatch(string(body), -1) {
		names = append(names, m[1])
		if len(names) == listSize {
			break
		}
	}
	return names, nil
}

// fetchPyPI reads the top-pypi-packages dataset.
func fetchPyPI() ([]string, error) {
	body, err := get("https://hugovk.github.io/top-pypi-packages/top-pypi-packages.min.json")
	if err != nil {
		return nil, err
	}
	var doc struct {
		Rows []struct {
			Project string `json:"project"`
		} `json:"rows"`
	}
	if err := json.Unmarshal(body, &doc); err != nil {
		return nil, err
	}
	var names []string
	for _, row := range doc.Rows {
		names = append(names, row.Project)
		if len(names) == listSize {
			break
		}
	}
	return names, nil
}

// fetchCrates pages the crates.io API by downloads, respecting the
// one-request-per-second guideline.
func fetchCrates() ([]string, error) {
	var names []string
	for page := 1; page <= listSize/100; page++ {
		url := fmt.Sprintf("https://crates.io/api/v1/crates?page=%d&per_page=100&sort=downloads", page)
		body, err := get(url)
		if err != nil {
			return nil, err
		}
		var doc struct {
			Crates []struct {
				ID string `json:"id"`
			} `json:"crates"`
		}
		if err := json.Unmarshal(body, &doc); err != nil {
			return nil, err
		}
		for _, crate := range doc.Crates {
			names = append(names, crate.ID)
		}
		time.Sleep(1100 * time.Millisecond)
	}
	return names, nil
}
